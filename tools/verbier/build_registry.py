"""Parse Appendix A (pistes) and B (lifts) of the Verbier 4 Vallees guide text into lib/verbier/registry-data.ts.
Run: python3 tools/verbier/build_registry.py tools/verbier/guide-2026-11-14.txt"""
import json, re, sys, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
text = open(sys.argv[1], encoding='utf-8').read()
def section(start, end): a = text.index(start); return text[a:text.index(end, a)]
def parse(block):
    rows, sector, cur = [], None, None
    for line in block.splitlines():
        m = re.match(r'^(Verbier|La Tzoumaz|Bruson|4 Vallées) — \d+ entries', line.strip())
        if m: sector = m.group(1); continue
        m = re.match(r'^\s+(\d{3})\s{2,}(.+?)\s{2,}(\S.*?)\s*$', line)
        if m:
            cur = dict(id=m.group(1), sector=sector, name=m.group(2).strip(), cls=m.group(3).strip()); rows.append(cur); continue
        m = re.match(r'^\s{20,}(\S.*?)(?:\s{2,}(\S.*?))?\s*$', line)
        if m and cur and not line.strip().startswith('-') and 'ID' not in line:
            cur['name'] += ' ' + m.group(1).strip()
            if m.group(2): cur['cls'] += ' ' + m.group(2).strip()
        if not line.strip(): cur = None
    return rows
pistes = parse(section('Appendix A Named piste and connection inventory', 'Appendix B Named lift inventory'))
lifts = parse(section('Appendix B Named lift inventory', 'Appendix C Elevation anchor registry'))
assert len(pistes) == 107, len(pistes)
assert len(lifts) == 35, len(lifts)
def fix(rows, known):
    for r in rows:
        if r['cls'] in known: continue
        whole = (r['name'] + ' ' + r['cls']).split()
        for k in sorted(known, key=len, reverse=True):
            kw = k.split()
            for i in range(len(whole) - len(kw), 0, -1):
                if whole[i:i + len(kw)] == kw:
                    r['name'] = ' '.join(whole[:i] + whole[i + len(kw):]); r['cls'] = k; break
            if r['cls'] == k: break
        assert r['cls'] in known, r
    return rows
CLS = {'Blue': 'blue', 'Red': 'red', 'Black': 'black', 'Yellow itinerary': 'itinerary', 'Connection': 'connection', 'Bus connection': 'bus-connection'}
pistes = fix(pistes, CLS)
# Table cells that wrap across lines in the guide's text export, reassembled and checked against the guide by hand.
CORRECTIONS = {'063': 'Greppon Blanc, piste des téléskis, partie supérieure (I et II)'}
for r in pistes:
    if r['id'] in CORRECTIONS: r['name'] = CORRECTIONS[r['id']]
LIFT_TYPES = ['Gondola', 'Funispace cable lift', 'Aerial cableway', '6-seat chair', '4-seat chair', '2-seat chair', 'Hybrid Télémixte', 'Surface lift', 'Magic carpet', 'Hybrid: 6-chair / 10-cabin']
lifts = fix(lifts, LIFT_TYPES)
out_p = [dict(id='piste-' + r['id'], sector=r['sector'], name=r['name'], classification=CLS[r['cls']], geometry=None) for r in pistes]
out_l = [dict(id='lift-' + r['id'], sector=r['sector'], name=r['name'], type=r['cls'], geometry=None) for r in lifts]
with open(os.path.join(ROOT, 'lib/verbier/registry-data.ts'), 'w', encoding='utf-8') as f:
    f.write('// GENERATED by tools/verbier/build_registry.py from the Verbier 4 Vallees guide (reference date 14 Nov 2026).\n')
    f.write('// Names and classes are transcribed as published. geometry is null: not supplied by the guide, never invented.\n')
    f.write('export const PISTES = ' + json.dumps(out_p, ensure_ascii=False) + ' as const;\n')
    f.write('export const LIFTS = ' + json.dumps(out_l, ensure_ascii=False) + ' as const;\n')
print(len(out_p), 'pistes', len(out_l), 'lifts')
for k in ('Blue', 'Red', 'Black', 'Yellow itinerary', 'Connection', 'Bus connection'): print(k, sum(1 for r in pistes if r['cls'] == k))
print(sorted(set(r['cls'] for r in lifts)))
print([p['name'] for p in out_p if len(p['name']) > 30])
